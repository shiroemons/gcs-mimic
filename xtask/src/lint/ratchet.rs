use super::{Finding, RATCHETED_CLIPPY_LINTS, RATCHETED_TEXT_RULES, production_file};
use std::{collections::BTreeMap, fmt, fs, path::Path};

pub(super) const FILE: &str = "xtask/lint-baseline.txt";

pub(super) fn eligible(rule: &str) -> bool {
    RATCHETED_CLIPPY_LINTS.contains(&rule) || RATCHETED_TEXT_RULES.contains(&rule)
}

#[derive(Debug, Default, PartialEq, Eq)]
pub(super) struct Baseline(BTreeMap<(String, String), usize>);

#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Scope {
    Host,
    Target,
}

#[derive(Debug)]
pub(super) enum Problem {
    Exceeded {
        rule: String,
        file: String,
        allowed: usize,
        findings: Vec<Finding>,
    },
    Stale {
        rule: String,
        file: String,
        recorded: usize,
        found: usize,
    },
}

impl fmt::Display for Problem {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Exceeded {
                rule,
                file,
                allowed,
                findings,
            } => {
                write!(
                    f,
                    "{rule}: {file}: {} findings exceed baseline {allowed}",
                    findings.len()
                )?;
                for finding in findings {
                    write!(
                        f,
                        "\nerror: {}: {}:{}",
                        finding.rule, finding.file, finding.line
                    )?;
                }
                Ok(())
            }
            Self::Stale {
                rule,
                file,
                recorded,
                found,
            } => {
                write!(
                    f,
                    "{rule}: {file}: stale baseline {recorded}, now {found}; "
                )?;
                if *found == 0 {
                    write!(f, "delete its {FILE} entry")
                } else {
                    write!(f, "lower {FILE} entry to: {rule}\t{file}\t{found}")
                }
            }
        }
    }
}

impl Baseline {
    pub(super) fn load(root: &Path) -> Result<Self, String> {
        let text =
            fs::read_to_string(root.join(FILE)).map_err(|error| format!("{FILE}: {error}"))?;
        Self::parse(&text)
    }

    fn parse(text: &str) -> Result<Self, String> {
        let mut entries = BTreeMap::new();
        for (index, line) in text.lines().enumerate() {
            if line.trim().is_empty() || line.starts_with('#') {
                continue;
            }
            let invalid = || {
                format!(
                    "{FILE}:{}: expected a unique ratcheted rule, production file and positive count separated by tabs",
                    index + 1
                )
            };
            let mut fields = line.split('\t');
            let rule = fields
                .next()
                .filter(|rule| eligible(rule))
                .ok_or_else(invalid)?;
            let file = fields
                .next()
                .filter(|file| production_file(file) && super::normalize(file) == *file)
                .ok_or_else(invalid)?;
            let count = fields
                .next()
                .and_then(|count| count.parse::<usize>().ok())
                .filter(|count| *count > 0)
                .ok_or_else(invalid)?;
            if fields.next().is_some()
                || entries
                    .insert((rule.to_owned(), file.to_owned()), count)
                    .is_some()
            {
                return Err(invalid());
            }
        }
        Ok(Self(entries))
    }

    pub(super) fn from_findings(findings: &[Finding]) -> Self {
        let mut entries = BTreeMap::new();
        for finding in findings.iter().filter(|finding| eligible(&finding.rule)) {
            *entries
                .entry((finding.rule.clone(), finding.file.clone()))
                .or_default() += 1;
        }
        Self(entries)
    }

    pub(super) fn render(&self) -> String {
        let mut text = "# rule\tfile\tcount — generated by `cargo xtask lint --baseline`; only lower counts by hand.\n".to_owned();
        for ((rule, file), count) in &self.0 {
            text.push_str(&format!("{rule}\t{file}\t{count}\n"));
        }
        text
    }

    pub(super) fn check(&self, findings: &[Finding], scope: Scope) -> Vec<Problem> {
        let current = Self::from_findings(findings);
        let mut pairs = self.0.clone();
        for pair in current.0.keys() {
            pairs.entry(pair.clone()).or_default();
        }
        pairs
            .into_iter()
            .filter_map(|((rule, file), allowed)| {
                let found = current
                    .0
                    .get(&(rule.clone(), file.clone()))
                    .copied()
                    .unwrap_or_default();
                if found > allowed {
                    let findings = findings
                        .iter()
                        .filter(|finding| finding.rule == rule && finding.file == file)
                        .cloned()
                        .collect();
                    Some(Problem::Exceeded {
                        rule,
                        file,
                        allowed,
                        findings,
                    })
                } else if found < allowed && scope == Scope::Host {
                    Some(Problem::Stale {
                        rule,
                        file,
                        recorded: allowed,
                        found,
                    })
                } else {
                    None
                }
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn finding(line: usize) -> Finding {
        Finding::new("clippy::indexing_slicing", "src/example.rs", line)
    }

    #[test]
    fn counts_cannot_increase_and_host_improvements_must_be_recorded() {
        let baseline = Baseline::from_findings(&[finding(1), finding(2)]);
        assert!(
            baseline
                .check(&[finding(10), finding(20)], Scope::Host)
                .is_empty()
        );
        let findings = [finding(1), finding(2), finding(3)];
        let problems = baseline.check(&findings, Scope::Host);
        assert!(
            matches!(problems.as_slice(), [Problem::Exceeded { allowed: 2, findings, .. }] if findings.len() == 3)
        );
        assert!(matches!(
            baseline.check(&[finding(1)], Scope::Host).as_slice(),
            [Problem::Stale {
                recorded: 2,
                found: 1,
                ..
            }]
        ));
        assert!(matches!(
            baseline.check(&[], Scope::Host).as_slice(),
            [Problem::Stale { found: 0, .. }]
        ));
        assert!(baseline.check(&[], Scope::Target).is_empty());
        assert!(matches!(
            baseline.check(&findings, Scope::Target).as_slice(),
            [Problem::Exceeded { .. }]
        ));
        assert!(
            !baseline
                .check(
                    &[Finding::new("clippy::indexing_slicing", "src/new.rs", 1)],
                    Scope::Target
                )
                .is_empty()
        );
    }

    #[test]
    fn baseline_format_round_trips_and_rejects_invalid_entries() {
        let baseline = Baseline::from_findings(&[
            finding(1),
            finding(2),
            Finding::new("text::static_str_error", "src/other.rs", 5),
        ]);
        assert_eq!(Baseline::parse(&baseline.render()).unwrap(), baseline);
        for text in [
            "clippy::indexing_slicing\tsrc/example.rs\tzero",
            "clippy::indexing_slicing\tsrc/example.rs\t0",
            "clippy::unwrap_used\tsrc/example.rs\t1",
            "unknown\tsrc/example.rs\t1",
            "clippy::indexing_slicing\tsrc/../outside.rs\t1",
            "clippy::indexing_slicing\tsrc/example.rs\t1\textra",
            "clippy::indexing_slicing\tsrc/example.rs\t1\nclippy::indexing_slicing\tsrc/example.rs\t2",
        ] {
            assert!(Baseline::parse(text).is_err(), "{text}");
        }
    }
}
