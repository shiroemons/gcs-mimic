//! Per-file ratchet on wall-clock calls in test code.
//!
//! Tests that sleep for a while, or poll against their own short deadline, pass or fail with
//! the speed of the machine, and shared CI runners stall for seconds. Tests wait for a state
//! through the shared helpers in `src/test_support.rs` (`eventually` and its variants), which
//! keep the only polling loop and a single hang guard. Every remaining `sleep(` or
//! `Instant::now()` call in a test file is counted; no file may gain one, and a file that loses
//! one must lower its recorded count so the gain cannot return.

use super::{mask, production_file};
use std::{collections::BTreeMap, fmt::Write as _, fs, path::Path};

pub(super) const FILE: &str = "xtask/test-clock-baseline.txt";

/// The shared wait helpers own the one sanctioned polling loop.
const HELPERS: [&str; 1] = ["src/test_support.rs"];
const CALLS: [&str; 2] = ["sleep(", "Instant::now()"];

/// Whether a repository-relative path is test code covered by the ratchet.
pub(super) fn test_file(path: &str) -> bool {
    path.ends_with(".rs")
        && !HELPERS.contains(&path)
        && (path.starts_with("tests/")
            || (path.starts_with("src/")
                && !production_file(path)
                && !path.starts_with("src/grpc/generated/")
                && !path.starts_with("src/grpc/codegen/")))
}

/// One-based lines of the wall-clock calls in `text`, ignoring comments and string literals.
pub(super) fn calls(text: &str) -> Vec<usize> {
    let masked = mask(text);
    let mut lines = Vec::new();
    for call in CALLS {
        for (offset, _) in masked.match_indices(call) {
            let before = masked[..offset].chars().next_back();
            if before.is_some_and(|c| c.is_alphanumeric() || c == '_') {
                continue;
            }
            lines.push(masked[..offset].matches('\n').count() + 1);
        }
    }
    lines.sort_unstable();
    lines
}

/// Per-file call lines for every test file under `src/` and `tests/`.
pub(super) fn scan(root: &Path) -> Result<BTreeMap<String, Vec<usize>>, String> {
    let mut found = BTreeMap::new();
    let mut pending = vec![root.join("src"), root.join("tests")];
    while let Some(directory) = pending.pop() {
        for entry in
            fs::read_dir(&directory).map_err(|e| format!("{}: {e}", directory.display()))?
        {
            let path = entry.map_err(|e| e.to_string())?.path();
            if path.is_dir() {
                pending.push(path);
                continue;
            }
            let Ok(relative) = path.strip_prefix(root) else {
                continue;
            };
            let relative = relative
                .components()
                .map(|c| c.as_os_str().to_string_lossy())
                .collect::<Vec<_>>()
                .join("/");
            if !test_file(&relative) {
                continue;
            }
            let text = fs::read_to_string(&path).map_err(|e| format!("{relative}: {e}"))?;
            let lines = calls(&text);
            if !lines.is_empty() {
                found.insert(relative, lines);
            }
        }
    }
    Ok(found)
}

pub(super) fn render(found: &BTreeMap<String, Vec<usize>>) -> String {
    let mut text = "# file\tcount — wall-clock calls in test code; generated by `cargo xtask lint --test-clock-baseline`; only lower counts by hand.\n".to_owned();
    for (file, lines) in found {
        let _ = writeln!(text, "{file}\t{}", lines.len());
    }
    text
}

pub(super) fn parse(text: &str) -> Result<BTreeMap<String, usize>, String> {
    let mut entries = BTreeMap::new();
    for (index, line) in text.lines().enumerate() {
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let invalid = || {
            format!(
                "{FILE}:{}: expected a unique test file and positive count separated by a tab",
                index + 1
            )
        };
        let (file, count) = line.split_once('\t').ok_or_else(invalid)?;
        let count = count
            .parse::<usize>()
            .ok()
            .filter(|count| *count > 0)
            .ok_or_else(invalid)?;
        if !test_file(file) || entries.insert(file.to_owned(), count).is_some() {
            return Err(invalid());
        }
    }
    Ok(entries)
}

/// Problems that fail the gate: files above their recorded count, and stale counts.
pub(super) fn check(
    baseline: &BTreeMap<String, usize>,
    found: &BTreeMap<String, Vec<usize>>,
) -> Vec<String> {
    let mut files: Vec<&String> = baseline.keys().chain(found.keys()).collect();
    files.sort_unstable();
    files.dedup();
    let mut problems = Vec::new();
    for file in files {
        let allowed = baseline.get(file).copied().unwrap_or_default();
        let lines = found.get(file).map_or(&[][..], Vec::as_slice);
        if lines.len() > allowed {
            let mut problem = format!(
                "test_clock: {file}: {} wall-clock calls exceed baseline {allowed}; wait through \
                 test_support::eventually* instead",
                lines.len()
            );
            for line in lines {
                let _ = write!(problem, "\nerror: test_clock: {file}:{line}");
            }
            problems.push(problem);
        } else if lines.len() < allowed {
            problems.push(if lines.is_empty() {
                format!("test_clock: {file}: stale baseline {allowed}, now 0; delete its {FILE} entry")
            } else {
                format!(
                    "test_clock: {file}: stale baseline {allowed}, now {}; lower {FILE} entry to: {file}\t{}",
                    lines.len(),
                    lines.len()
                )
            });
        }
    }
    problems
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn counts_calls_outside_comments_strings_and_longer_names() {
        let text = "fn a() {\n    std::thread::sleep(d);\n    // tokio::time::sleep(d)\n    let s = \"sleep(\";\n    let t = Instant::now();\n    deep_sleep(1);\n    tokio::time::sleep(d).await;\n}\n";
        assert_eq!(calls(text), [2, 5, 7]);
    }

    #[test]
    fn counts_calls_after_block_comments_with_multibyte_text() {
        assert_eq!(calls("/* é */ sleep(d);"), [1]);
    }

    #[test]
    fn covers_test_files_but_not_production_or_the_shared_helpers() {
        assert!(test_file("tests/it_protocol/object_http.rs"));
        assert!(test_file("src/storage/resumable_http_tests.rs"));
        assert!(test_file("src/server/admin/sync/tests.rs"));
        assert!(!test_file("src/server.rs"));
        assert!(!test_file("src/test_support.rs"));
        assert!(!test_file("src/grpc/generated/google.storage.v2.rs"));
        assert!(!test_file("tests/fixtures/data.json"));
    }

    #[test]
    fn rejects_new_calls_and_stale_counts() {
        let found = BTreeMap::from([("tests/a.rs".to_owned(), vec![3, 9])]);
        let exceeded = check(&BTreeMap::from([("tests/a.rs".to_owned(), 1)]), &found);
        assert_eq!(exceeded.len(), 1);
        assert!(exceeded[0].contains("2 wall-clock calls exceed baseline 1"));
        assert!(exceeded[0].ends_with("tests/a.rs:9"));
        let stale = check(&BTreeMap::from([("tests/a.rs".to_owned(), 3)]), &found);
        assert!(stale[0].ends_with("lower xtask/test-clock-baseline.txt entry to: tests/a.rs\t2"));
        let gone = check(
            &BTreeMap::from([("tests/b.rs".to_owned(), 1)]),
            &BTreeMap::new(),
        );
        assert!(gone[0].ends_with("delete its xtask/test-clock-baseline.txt entry"));
        assert!(check(&BTreeMap::from([("tests/a.rs".to_owned(), 2)]), &found).is_empty());
    }

    #[test]
    fn baseline_round_trips_and_rejects_invalid_lines() {
        let found = BTreeMap::from([("tests/a.rs".to_owned(), vec![1, 2])]);
        assert_eq!(
            parse(&render(&found)).unwrap(),
            BTreeMap::from([("tests/a.rs".to_owned(), 2)])
        );
        for invalid in [
            "tests/a.rs",
            "tests/a.rs\t0",
            "src/server.rs\t1",
            "tests/a.rs\t1\ntests/a.rs\t1",
        ] {
            assert!(parse(invalid).is_err(), "{invalid}");
        }
    }
}
