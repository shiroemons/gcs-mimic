#!/usr/bin/env bash
# Publishes what `cargo xtask dependencies update-images` produced in an unprivileged job as one
# pull request on a branch only this script writes. Usage: propose-image-refresh.sh RECORD PATCH,
# where RECORD holds the command's stdout, empty when no image changed, and PATCH the resulting
# working tree diff. This script runs with write access, so it compiles and runs nothing from the
# patch.
set -euo pipefail

record=$1
patch=$2
branch=automation/image-digests
ledger=compatibility/dependency-status.json

# --head also matches a fork's branch of the same name, which this script must never edit or close.
open_pr=$(gh pr list --head "$branch" --state open --json number,isCrossRepository \
  --jq '[.[] | select(.isCrossRepository | not)][0].number // empty')

if [[ ! -s $record ]]; then
  if [[ -n $open_pr ]]; then
    gh pr close "$open_pr" --delete-branch \
      --comment 'The pins on main already match the registry, so this proposal is obsolete.'
  fi
  exit 0
fi

bash scripts/apply-pin-patch.sh "$patch"

gh auth setup-git

# The record carries a timestamp, so comparing whole trees would re-run the expensive checks every
# day for the same digests. A proposal that still applies keeps its existing results.
if [[ -n $open_pr ]] && [[ $(gh pr view "$open_pr" --json mergeable --jq .mergeable) != CONFLICTING ]]; then
  git fetch --quiet --depth=1 origin "$branch"
  if [[ $(jq -c .docker "$ledger") == "$(git show "FETCH_HEAD:$ledger" | jq -c .docker)" ]]; then
    echo "Pull request #$open_pr already proposes these pins."
    exit 0
  fi
fi

git config user.name 'github-actions[bot]'
git config user.email '41898282+github-actions[bot]@users.noreply.github.com'
git switch --force-create "$branch"
git commit --quiet --message 'chore(deps): adopt container images rebuilt under unchanged tags'
git push --force origin "HEAD:refs/heads/$branch"

body=$(mktemp)
{
  cat "$record"
  printf '\nGenerated by the daily **Dependency freshness** workflow. '
  printf 'A push made with the workflow token starts no workflow, so that workflow dispatches '
  printf 'Foundation and Documentation checks on this branch; review their results before merging. '
  printf 'Newer versions behind a moving tag and images pinned in workflows are not part of this proposal.\n'
} >"$body"
if [[ -n $open_pr ]]; then
  gh pr edit "$open_pr" --body-file "$body"
else
  gh pr create --base main --head "$branch" \
    --title 'chore(deps): adopt container images rebuilt under unchanged tags' \
    --body-file "$body"
fi

gh workflow run ci.yaml --ref "$branch"
gh workflow run docs.yaml --ref "$branch"
